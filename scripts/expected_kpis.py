"""Compute the expected values of the main DAX measures directly from the CSV files.

Purpose: a test oracle. After building or changing the report (by hand or with
Claude Code), the numbers shown in Power BI must match docs/expected-kpis.md.

Usage:  python scripts/expected_kpis.py          (requires pandas)
Output: docs/expected-kpis.md and docs/expected-kpis.json
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
DOCS = ROOT / "docs"


def load(name):
    return pd.read_csv(DATA / f"{name}.csv", encoding="utf-8-sig")


fs = load("FactScreening")
fe = load("FactEyeExam")
ft = load("FactTarget")
bs = load("BridgeSymptom")
school = load("DimSchool")
commune = load("DimCommune")
pref = load("DimPrefecture")
region = load("DimRegion")

fs["Year"] = fs["DateKey"] // 10000
ft["Year"] = ft["DateKey"] // 10000
geo = school.merge(commune, on="CommuneKey").merge(pref, on="PrefectureKey").merge(region, on="RegionKey")
fs = fs.merge(geo[["SchoolKey", "PrefectureKey", "Prefecture", "RegionCode", "RegionName_EN", "RegionSortOrder"]], on="SchoolKey")

need_students = set(fe.loc[(fe["SphereRx"] != 0) | (fe["CylinderRx"] != 0), "StudentKey"])
impair_students = set(fe.loc[fe["VACategoryKey"] >= 2, "StudentKey"])
symptom_students = set(bs["StudentKey"])
fs["Need"] = fs["StudentKey"].isin(need_students)
fs["Impair"] = fs["StudentKey"].isin(impair_students)
fs["Symptom"] = fs["StudentKey"].isin(symptom_students)


def kpis(df, targets):
    n = len(df)
    need = int(df["Need"].sum())
    return {
        "students_screened": n,
        "correction_need_rate": need / n if n else None,
        "uncorrected_need_rate": int((df["Need"] & (df["WearsCorrection"] == 0)).sum()) / need if need else None,
        "impairment_rate": df["Impair"].mean() if n else None,
        "screen_exposure_rate": (df["ScreenTimeKey"] > 0).mean() if n else None,
        "symptom_rate": df["Symptom"].mean() if n else None,
        "target_students": float(targets["TargetStudents"].sum()),
        "target_achievement": n / targets["TargetStudents"].sum() if targets["TargetStudents"].sum() else None,
    }


out = {"by_campaign": {}, "by_region_2026": {}, "data_quality": {}}
for y in sorted(fs["Year"].unique()):
    out["by_campaign"][int(y)] = kpis(fs[fs["Year"] == y], ft[ft["Year"] == y])
out["all_campaigns"] = kpis(fs, ft)

ft_geo = ft.merge(pref[["PrefectureKey", "RegionKey"]], on="PrefectureKey").merge(region, on="RegionKey")
for _, r in region.sort_values("RegionSortOrder").iterrows():
    sub = fs[(fs["Year"] == 2026) & (fs["RegionCode"] == r["RegionCode"])]
    tg = ft_geo[(ft_geo["Year"] == 2026) & (ft_geo["RegionCode"] == r["RegionCode"])]
    out["by_region_2026"][r["RegionName_EN"]] = kpis(sub, tg)

eyes = fe.groupby("StudentKey").size()
out["data_quality"] = {
    "implausible_cylinder": int((fe["CylinderRx"].abs() > 6).sum()),
    "plus_cylinder_convention": int(((fe["CylinderRx"] > 0) & (fe["CylinderRx"] <= 6)).sum()),
    "missing_visual_acuity": int(fe["VA_10"].isna().sum()),
    "students_without_two_eyes": int((fs["StudentKey"].map(eyes).fillna(0) != 2).sum()),
    "symptom_inconsistency": int(((fs["HasSymptoms"] == 0) & fs["Symptom"]).sum()),
}
out["data_quality"]["total"] = sum(out["data_quality"].values())

DOCS.mkdir(exist_ok=True)
(DOCS / "expected-kpis.json").write_text(json.dumps(out, indent=2, default=float), encoding="utf-8")


def pct(x):
    return "" if x is None else f"{x * 100:.1f}%"


def yoy(cur, prev):
    return f"{(cur - prev) / prev * 100:+.1f}%"


lines = [
    "# Expected KPI values (test oracle)",
    "",
    "Generated by `scripts/expected_kpis.py` from the CSV files. The report must show these values",
    "(rounded as in the visuals). A mismatch means a modelling or DAX error, not a design choice.",
    "",
    "## By campaign (no other filter)",
    "",
    "| Measure | 2024 | 2025 | 2026 | All |",
    "|---|---:|---:|---:|---:|",
]
camp = out["by_campaign"]
cols = [camp[2024], camp[2025], camp[2026], out["all_campaigns"]]
rows = [
    ("Students Screened", lambda k: f"{k['students_screened']:,}"),
    ("Correction Need Rate", lambda k: pct(k["correction_need_rate"])),
    ("Uncorrected Need Rate", lambda k: pct(k["uncorrected_need_rate"])),
    ("Impairment Rate", lambda k: pct(k["impairment_rate"])),
    ("Screen Exposure Rate", lambda k: pct(k["screen_exposure_rate"])),
    ("Symptom Rate", lambda k: pct(k["symptom_rate"])),
    ("Target Students", lambda k: f"{k['target_students']:,.0f}"),
    ("Target Achievement %", lambda k: pct(k["target_achievement"])),
]
for name, f in rows:
    lines.append(f"| `{name}` | " + " | ".join(f(k) for k in cols) + " |")
lines += [
    "",
    f"- `Students Screened YoY %` 2025: {yoy(camp[2025]['students_screened'], camp[2024]['students_screened'])}, "
    f"2026: {yoy(camp[2026]['students_screened'], camp[2025]['students_screened'])}",
    f"- `Correction Need Rate Change (pts)` 2025: {(camp[2025]['correction_need_rate'] - camp[2024]['correction_need_rate']) * 100:+.1f}, "
    f"2026: {(camp[2026]['correction_need_rate'] - camp[2025]['correction_need_rate']) * 100:+.1f}",
    "",
    "## By region, 2026 campaign",
    "",
    "| Region | Screened | Need rate | Impairment | Target achievement |",
    "|---|---:|---:|---:|---:|",
]
for name, k in out["by_region_2026"].items():
    lines.append(f"| {name} | {k['students_screened']:,} | {pct(k['correction_need_rate'])} | {pct(k['impairment_rate'])} | {pct(k['target_achievement'])} |")
dq = out["data_quality"]
lines += [
    "",
    "## Data integrity checks (whole model)",
    "",
    "| Measure | Expected |",
    "|---|---:|",
    f"| `DQ Implausible Cylinder` | {dq['implausible_cylinder']} |",
    f"| `DQ Plus Cylinder Convention` | {dq['plus_cylinder_convention']} |",
    f"| `DQ Missing Visual Acuity` | {dq['missing_visual_acuity']} |",
    f"| `DQ Students Without Two Eyes` | {dq['students_without_two_eyes']} |",
    f"| `DQ Symptom Inconsistency` | {dq['symptom_inconsistency']} |",
    f"| `DQ Issues Total` | {dq['total']} |",
    "",
]
(DOCS / "expected-kpis.md").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
